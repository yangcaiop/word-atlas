import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, loadEnv } from "vite";
import { validateConfig } from "../edge/handler.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const env = { ...loadEnv("pages", root, "ATLAS_"), ...process.env };
if (env.ATLAS_BASE && env.ATLAS_BASE !== "/") {
  throw new Error(
    "ESA Pages 使用独立域名根路径；子路径部署请使用原有 npm run build。",
  );
}
const config = validateConfig({
  apiOrigin: env.ATLAS_API_ORIGIN || "https://word-api.yckara.top",
  ossBaseUrl:
    env.ATLAS_OSS_BASE_URL ||
    "https://word-atlas-oss.oss-cn-shenzhen.aliyuncs.com/word-atlas",
  mediaCacheVersion: env.ATLAS_MEDIA_CACHE_VERSION || "v1",
});
process.chdir(root);
await build({ mode: "pages" });
const output = path.join(root, "dist-pages");
const resources = [
  "manifest.webmanifest",
  "favicon.svg",
  "sw.js",
  "icon-512.png",
  "brand",
  "sfx",
  "atlas/index.json",
  "atlas/entries",
];
for (const name of resources) {
  await fs.mkdir(path.dirname(path.join(output, name)), { recursive: true });
  await fs.cp(path.join(root, "public", name), path.join(output, name), {
    recursive: true,
    filter: (source) => !path.basename(source).startsWith("."),
  });
}
await fs.copyFile(
  path.join(root, "CONTENT_LICENSE.md"),
  path.join(output, "CONTENT_LICENSE.md"),
);
await fs.writeFile(
  path.join(root, "edge/config.generated.js"),
  `// Generated by build:pages. Public origin addresses only.\nexport default ${JSON.stringify(config, null, 2)};\n`,
);

async function files(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) return files(absolute);
      return [
        {
          path: path.relative(output, absolute),
          bytes: (await fs.stat(absolute)).size,
        },
      ];
    }),
  );
  return nested.flat();
}
const all = await files(output);
if (all.length > 2000 || all.some((file) => file.bytes > 25 * 1024 * 1024)) {
  throw new Error("Pages 构建超出 2000 文件或单文件 25 MB 限制。");
}
console.log(
  JSON.stringify(
    {
      output: "dist-pages",
      files: all.length,
      megabytes: +(
        all.reduce((sum, file) => sum + file.bytes, 0) /
        1024 /
        1024
      ).toFixed(2),
      ...config,
    },
    null,
    2,
  ),
);
